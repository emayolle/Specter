#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate the xlua.dll Lua C API forwarding layer.

The game ships its LuaJIT 5.1 C API inside `xlua.dll` (188 `lua*` exports). We
never link it as an import: Specter.Internal.dll is manual-mapped, and the
project rule is that every import must be resident *before* mapping (see
render/d3dcompiler_shim.cpp). Instead, each API function becomes a thunk that
forwards to a pointer resolved from `xlua.dll` at runtime with GetProcAddress --
exactly the pattern features/lua_console.cpp already uses by hand for the 13
functions it needs, generalized to the whole surface LuaBridge requires.

The thunk signatures are taken from the **vendored LuaJIT headers**
(third_party/luajit/include), NOT from PUC-Lua 5.1, so they match the game's
ABI (e.g. LuaJIT declares `void lua_pushstring(...)`).

Usage:
    python3 tools/gen_lua_thunks.py            # (re)write lua/thunks.cpp
    python3 tools/gen_lua_thunks.py --check     # verify it is up to date (CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
INCLUDE = ROOT / "third_party/luajit/include"
OUT = ROOT / "src/Specter.Internal/lua/thunks.cpp"
HDRS = ["lua.h", "lauxlib.h", "lualib.h"]

# Declared by LuaJIT but not exported by xlua.dll and unused by LuaBridge; a
# missing binding is not an error (see bind()).
OPTIONAL = {"lua_setlevel"}

# Variadic functions cannot be forwarded verbatim; they are reimplemented below
# on top of their non-variadic primitives.
MANUAL_VARIADIC = {"lua_pushfstring", "luaL_error"}

DECL = re.compile(r"(?:LUA_API|LUALIB_API|LUAMOD_API)\s+(?P<body>[^;]*);", re.S)
TAIL = re.compile(r"\(?\s*(?P<name>lua\w+)\s*\)?\s*\((?P<args>[^)]*)\)\s*$", re.S)

BANNER = (
    "// AUTO-GENERATED by tools/gen_lua_thunks.py - DO NOT EDIT.\n"
    "//\n"
    "// xlua.dll (LuaJIT 5.1) C API forwarding layer: every function below is a\n"
    "// thunk over a pointer resolved from xlua.dll at runtime, so the DLL adds\n"
    "// no import on xlua.dll (manual-map safe). Regenerate after bumping the\n"
    "// vendored LuaJIT headers:\n"
    "//\n"
    "//     python3 tools/gen_lua_thunks.py\n"
)


def parse():
    funcs = []
    for h in HDRS:
        text = (INCLUDE / h).read_text(encoding="utf-8")
        for m in DECL.finditer(text):
            body = " ".join(m.group("body").split())
            t = TAIL.search(body)
            if not t:
                continue
            name = t.group("name")
            args = " ".join(t.group("args").split())
            if args == "void":
                args = ""
            ret = body[: t.start()].strip()
            funcs.append({"ret": ret, "name": name, "args": args,
                          "variadic": "..." in args})
    # de-dup by name, first wins
    seen, out = set(), []
    for f in funcs:
        if f["name"] in seen:
            continue
        seen.add(f["name"])
        out.append(f)
    return out


def argname(a):
    a = a.strip()
    m = re.search(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*$", a)
    return m.group(1) if m else a


def forward_args(args):
    if not args:
        return ""
    return ", ".join(argname(a) for a in args.split(","))


def generate(funcs):
    real = [f for f in funcs if not f["variadic"]]
    lines = [BANNER, "#include <Windows.h>", "#include <cstdarg>",
             "#include <cstdio>", "#include <cstring>", "", '#include "lua.h"',
             '#include "lauxlib.h"', '#include "lualib.h"', "", "namespace {", "",
             "template <typename T> void bind(void* mod, const char* name, T& p) {",
             "    p = reinterpret_cast<T>(::GetProcAddress(",
             "        static_cast<HMODULE>(mod), name));",
             "}", "", "}  // namespace", ""]

    # pointer storage (left-aligned so the generated file stays readable)
    for f in real:
        a = f"({f['args']})" if f["args"] else "()"
        lines.append(f"static {f['ret']} (__cdecl *p_{f['name']}){a} = nullptr;")
    lines.append("")

    # forwarders
    for f in real:
        if f["args"]:
            lines.append(
                f"{f['ret']} {f['name']}({f['args']}) "
                f"{{ return p_{f['name']}({forward_args(f['args'])}); }}")
        else:
            lines.append(f"{f['ret']} {f['name']}() {{ return p_{f['name']}(); }}")
    lines.append("")

    # variadic, reimplemented on top of non-variadic primitives
    lines += [
        "// Variadic functions format the message here, then delegate.",
        "int luaL_error(lua_State* L, const char* fmt, ...) {",
        "    va_list ap; va_start(ap, fmt);",
        "    char buf[1024];",
        "    vsnprintf(buf, sizeof(buf), fmt, ap);",
        "    va_end(ap);",
        "    luaL_where(L, 1);",
        "    lua_pushstring(L, buf);",
        "    lua_concat(L, 2);",
        "    return lua_error(L);",
        "}",
        "",
        "const char* lua_pushfstring(lua_State* L, const char* fmt, ...) {",
        "    va_list ap; va_start(ap, fmt);",
        "    char buf[1024];",
        "    vsnprintf(buf, sizeof(buf), fmt, ap);",
        "    va_end(ap);",
        "    lua_pushstring(L, buf);",
        "    return lua_tolstring(L, -1, nullptr);",
        "}",
        "",
    ]

    # binder
    lines += [
        "namespace {",
        "char g_missing[1024];",
        "void note_missing(const char* name) {",
        "    std::size_t n = std::strlen(g_missing);",
        "    std::snprintf(g_missing + n, sizeof(g_missing) - n, \"%s%s\",",
        "                  n ? \", \" : \"\", name);",
        "}",
        "}  // namespace",
        "",
        "// Resolve every API pointer from `hmodule`. Returns the number of",
        "// functions that failed to resolve (excluding OPTIONAL ones); the",
        "// missing names land in specter_lua_missing().",
        "extern \"C\" int specter_lua_bind(void* hmodule) {",
        "    g_missing[0] = '\\0';",
        "    int bad = 0;",
    ]
    for f in real:
        opt = "true" if f["name"] in OPTIONAL else "false"
        lines.append(f"    bind(hmodule, \"{f['name']}\", p_{f['name']});")
        lines.append(
            f"    if (!p_{f['name']} && !({opt})) {{ note_missing(\"{f['name']}\"); ++bad; }}")
    lines += ["    return bad;", "}", "",
              "extern \"C\" const char* specter_lua_missing() { return g_missing; }",
              ""]
    return "\n".join(lines) + "\n"


def main():
    funcs = parse()
    text = generate(funcs)
    if "--check" in sys.argv:
        if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
            print("up to date (no change)")
            return 0
        print("OUT OF DATE: run python3 tools/gen_lua_thunks.py")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    n_thunk = len([f for f in funcs if not f["variadic"]])
    print(f"generated {OUT.relative_to(ROOT)}: {n_thunk} thunks "
          f"+ {len(MANUAL_VARIADIC)} variadic, {len(OPTIONAL)} optional")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
